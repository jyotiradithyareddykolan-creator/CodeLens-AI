"""Guards against drift between Alembic migrations and the SQLAlchemy models.

Runs on SQLite. PostgreSQL-specific parts (pgvector column type) are not covered here.
"""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config

from app.core.config import settings

BACKEND_DIR = Path(__file__).resolve().parents[1]


def alembic_config() -> Config:
    # No ini file: avoids alembic.ini's logging config reconfiguring pytest's loggers.
    cfg = Config()
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    return cfg


def test_migrations_upgrade_downgrade_and_match_models(tmp_path, monkeypatch):
    db_url = f"sqlite:///{(tmp_path / 'migrations.db').as_posix()}"
    monkeypatch.setattr(settings, "DATABASE_URL", db_url)
    cfg = alembic_config()

    command.upgrade(cfg, "head")
    # Raises AutogenerateDiffsDetected if models and migrations disagree.
    command.check(cfg)

    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    command.check(cfg)


def test_migration_history_is_linear():
    from alembic.script import ScriptDirectory

    heads = ScriptDirectory.from_config(alembic_config()).get_heads()
    assert len(heads) == 1, f"Multiple Alembic heads: {heads}"
