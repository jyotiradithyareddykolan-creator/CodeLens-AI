import pytest

from app.core.config import settings
from app.indexing.file_filter import SkipReason, classify_content, classify_path


@pytest.mark.parametrize(
    "path,language",
    [
        ("app/main.py", "python"),
        ("src/index.js", "javascript"),
        ("src/App.jsx", "javascript"),
        ("lib/x.mjs", "javascript"),
        ("lib/x.cjs", "javascript"),
        ("src/api.ts", "typescript"),
        ("src/types.d.ts", "typescript"),
        ("src/Page.tsx", "tsx"),
        ("SRC/UPPER.PY", "python"),
        ("deep/nested/dir/module.py", "python"),
    ],
)
def test_supported_source_files_are_included(path, language):
    decision = classify_path(path, size=100)
    assert decision.included
    assert decision.language == language


@pytest.mark.parametrize(
    "path,reason",
    [
        ("README.md", SkipReason.UNSUPPORTED_LANGUAGE),
        ("logo.png", SkipReason.UNSUPPORTED_LANGUAGE),
        ("package-lock.json", SkipReason.UNSUPPORTED_LANGUAGE),
        ("Makefile", SkipReason.UNSUPPORTED_LANGUAGE),
        ("node_modules/react/index.js", SkipReason.EXCLUDED_DIRECTORY),
        ("frontend/node_modules/a/b.ts", SkipReason.EXCLUDED_DIRECTORY),
        ("dist/app.js", SkipReason.EXCLUDED_DIRECTORY),
        ("build/lib/x.py", SkipReason.EXCLUDED_DIRECTORY),
        ("vendor/lib.js", SkipReason.EXCLUDED_DIRECTORY),
        ("venv/lib/site.py", SkipReason.EXCLUDED_DIRECTORY),
        ("pkg/__pycache__/m.py", SkipReason.EXCLUDED_DIRECTORY),
        ("my_pkg.egg-info/x.py", SkipReason.EXCLUDED_DIRECTORY),
        ("web/.next/server.js", SkipReason.EXCLUDED_DIRECTORY),
        ("static/app.min.js", SkipReason.EXCLUDED_PATTERN),
        ("static/app.js.map", SkipReason.EXCLUDED_PATTERN),
        ("proto/user_pb2.py", SkipReason.EXCLUDED_PATTERN),
        ("api/client.generated.ts", SkipReason.EXCLUDED_PATTERN),
        (".env", SkipReason.SENSITIVE_FILENAME),
        ("config/.env.production", SkipReason.SENSITIVE_FILENAME),
        ("certs/server.pem", SkipReason.SENSITIVE_FILENAME),
        ("keys/deploy.key", SkipReason.SENSITIVE_FILENAME),
        ("settings/local_settings.py", SkipReason.SENSITIVE_FILENAME),
        ("../escape.py", SkipReason.INVALID_PATH),
        ("/abs/path.py", SkipReason.INVALID_PATH),
        ("a//b.py", SkipReason.INVALID_PATH),
        ("win\\path.py", SkipReason.INVALID_PATH),
        ("", SkipReason.INVALID_PATH),
    ],
)
def test_irrelevant_or_unsafe_paths_are_excluded(path, reason):
    decision = classify_path(path, size=100)
    assert not decision.included
    assert decision.skip_reason == reason


def test_directory_names_only_match_whole_segments():
    # "builder" and "distance" are not "build"/"dist".
    assert classify_path("builder/core.py", size=10).included
    assert classify_path("src/distance.ts", size=10).included


def test_symlinks_submodules_size_limits():
    assert classify_path("link.py", mode="120000").skip_reason == SkipReason.SYMLINK
    assert classify_path("sub", mode="160000", entry_type="commit").skip_reason == SkipReason.SUBMODULE
    assert classify_path("empty.py", size=0).skip_reason == SkipReason.EMPTY
    too_big = settings.MAX_FILE_SIZE_BYTES + 1
    assert classify_path("big.py", size=too_big).skip_reason == SkipReason.TOO_LARGE
    assert classify_path("edge.py", size=settings.MAX_FILE_SIZE_BYTES).included


def test_content_is_decoded_when_indexable():
    assert classify_content(b"def f():\n    return 1\n") == "def f():\n    return 1\n"
    # UTF-8 BOM is stripped so line numbers and parsing are unaffected.
    assert classify_content("﻿x = 1\n".encode("utf-8")) == "x = 1\n"
    assert classify_content("name = 'café'\n".encode("utf-8")) == "name = 'café'\n"


@pytest.mark.parametrize(
    "data,reason",
    [
        (b"", SkipReason.EMPTY),
        (b"\x89PNG\r\n\x1a\n\x00\x00\x00", SkipReason.BINARY),
        ("x = 'caf\xe9'\n".encode("latin-1"), SkipReason.NON_UTF8),
        (b"// Code generated by protoc-gen-ts. DO NOT EDIT.\nexport const x = 1;\n", SkipReason.GENERATED),
        (b"# @generated by tool\nx = 1\n", SkipReason.GENERATED),
        (b"var a=1;" * 600, SkipReason.MINIFIED),
    ],
)
def test_content_filters(data, reason):
    assert classify_content(data) == reason


def test_generated_marker_must_be_in_file_header():
    body = "x = 1\n" * 50 + "# this mentions @generated far below the header\n"
    assert isinstance(classify_content(body.encode()), str)


def test_content_over_size_limit_is_rejected(monkeypatch):
    monkeypatch.setattr(settings, "MAX_FILE_SIZE_BYTES", 10)
    assert classify_content(b"x = 1234567890\n") == SkipReason.TOO_LARGE
