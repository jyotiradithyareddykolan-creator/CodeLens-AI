POSTGRES_URL = os.environ.get("CODELENS_TEST_POSTGRES_URL")

pytestmark = pytest.mark.skipif(
    not POSTGRES_URL, reason="CODELENS_TEST_POSTGRES_URL not set (live PostgreSQL tests)"
)


def async_url(url: str) -> str:
    return url.replace("postgresql+psycopg://", "postgresql+asyncpg://", 1)


@pytest.fixture(scope="module")
def migrated_postgres():
    """Fresh schema built by Alembic (not create_all) on the disposable database."""
    original = settings.DATABASE_URL
    settings.DATABASE_URL = POSTGRES_URL
    try:
        cfg = alembic_config()
        command.downgrade(cfg, "base")
        command.upgrade(cfg, "head")
        yield cfg
        command.downgrade(cfg, "base")
    finally:
        settings.DATABASE_URL = original


