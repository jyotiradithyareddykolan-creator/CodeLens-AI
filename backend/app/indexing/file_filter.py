"""Decide which repository files are worth indexing.

Two stages, so most files are rejected before any content is downloaded:

1. :func:`classify_path` uses only tree metadata (path, mode, type, size).
2. :func:`classify_content` inspects the downloaded bytes (binary, encoding,
   generated/minified code). Secret screening lives in ``secret_scanner``.

Languages are registered in :data:`LANGUAGES_BY_EXTENSION`; adding a language for
parsing later only requires a new entry here plus a Tree-sitter grammar.
"""

from dataclasses import dataclass
from enum import Enum
from pathlib import PurePosixPath
from typing import Optional, Union

from app.core.config import settings


class SkipReason(str, Enum):
    UNSUPPORTED_LANGUAGE = "unsupported_language"
    EXCLUDED_DIRECTORY = "excluded_directory"
    EXCLUDED_PATTERN = "excluded_pattern"
    SENSITIVE_FILENAME = "sensitive_filename"
    TOO_LARGE = "too_large"
    EMPTY = "empty"
    SYMLINK = "symlink"
    SUBMODULE = "submodule"
    INVALID_PATH = "invalid_path"
    BINARY = "binary"
    NON_UTF8 = "non_utf8"
    GENERATED = "generated"
    MINIFIED = "minified"
    SECRET_DETECTED = "secret_detected"
    FETCH_FAILED = "fetch_failed"


# Extension -> language identifier used by the parser (Milestone 2).
LANGUAGES_BY_EXTENSION = {
    ".py": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".ts": "typescript",
    ".mts": "typescript",
    ".cts": "typescript",
    ".tsx": "tsx",
}

# Any path segment with one of these names excludes everything below it.
EXCLUDED_DIRECTORIES = frozenset(
    {
        # dependencies / vendored code
        "node_modules", "bower_components", "jspm_packages", "vendor", "third_party",
        "site-packages", ".venv", "venv", "virtualenv", ".tox", ".nox", ".eggs", "Pods",
        # build output
        "dist", "build", "out", "target", ".next", ".nuxt", ".svelte-kit", ".output",
        ".turbo", ".parcel-cache", ".vite", ".angular", "storybook-static",
        # caches / tooling / VCS / IDE
        "__pycache__", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".cache",
        "coverage", "htmlcov", ".nyc_output", ".git", ".hg", ".svn", ".idea", ".vscode",
        ".gradle",
    }
)
EXCLUDED_DIRECTORY_SUFFIXES = (".egg-info",)

# File name suffixes that indicate bundled, minified or generated artefacts.
EXCLUDED_FILE_SUFFIXES = (
    ".min.js", ".min.mjs", ".min.cjs", "-min.js", ".bundle.js", ".chunk.js",
    ".map", "_pb2.py", "_pb2_grpc.py", ".pb.ts", "_pb.js", "_pb.d.ts",
    ".generated.ts", ".generated.js", ".generated.py",
)

# File names that commonly hold credentials. Never downloaded.
SENSITIVE_FILENAMES = frozenset(
    {
        ".env", ".envrc", ".netrc", ".npmrc", ".pypirc", ".pgpass", "id_rsa", "id_dsa",
        "id_ecdsa", "id_ed25519", "credentials", "credentials.json", "secrets.json",
        "service-account.json", "service_account.json", "local_settings.py",
    }
)
SENSITIVE_SUFFIXES = (".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".env")
SENSITIVE_PREFIXES = (".env.",)  # .env.local, .env.production, ...

GIT_MODE_SYMLINK = "120000"
GIT_MODE_SUBMODULE = "160000"

GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "auto-generated",
    "autogenerated",
    "this file is generated",
    "this file was automatically generated",
)
BINARY_SNIFF_BYTES = 8000


@dataclass(frozen=True)
class PathDecision:
    language: Optional[str] = None
    skip_reason: Optional[SkipReason] = None

    @property
    def included(self) -> bool:
        return self.skip_reason is None


def is_excluded_directory(dir_path: str) -> bool:
    """True if any segment of ``dir_path`` is an excluded directory."""
    for part in PurePosixPath(dir_path).parts:
        if part in EXCLUDED_DIRECTORIES or part.endswith(EXCLUDED_DIRECTORY_SUFFIXES):
            return True
    return False


def is_sensitive_filename(name: str) -> bool:
    lower = name.lower()
    return (
        lower in SENSITIVE_FILENAMES
        or lower.endswith(SENSITIVE_SUFFIXES)
        or lower.startswith(SENSITIVE_PREFIXES)
    )


def _valid_path(path: str) -> bool:
    if not path or len(path) > 1024 or path.startswith("/") or "\x00" in path or "\\" in path:
        return False
    return all(part not in ("", ".", "..") for part in path.split("/"))


def classify_path(path: str, mode: str = "100644", entry_type: str = "blob",
                  size: Optional[int] = None) -> PathDecision:
    """Classify a git tree entry using metadata only."""
    if not _valid_path(path):
        return PathDecision(skip_reason=SkipReason.INVALID_PATH)
    if entry_type == "commit" or mode == GIT_MODE_SUBMODULE:
        return PathDecision(skip_reason=SkipReason.SUBMODULE)
    if mode == GIT_MODE_SYMLINK:
        return PathDecision(skip_reason=SkipReason.SYMLINK)

    pure = PurePosixPath(path)
    if is_excluded_directory(str(pure.parent)):
        return PathDecision(skip_reason=SkipReason.EXCLUDED_DIRECTORY)
    if is_sensitive_filename(pure.name):
        return PathDecision(skip_reason=SkipReason.SENSITIVE_FILENAME)

    lower_name = pure.name.lower()
    if lower_name.endswith(EXCLUDED_FILE_SUFFIXES):
        return PathDecision(skip_reason=SkipReason.EXCLUDED_PATTERN)

    language = LANGUAGES_BY_EXTENSION.get(pure.suffix.lower())
    if language is None:
        return PathDecision(skip_reason=SkipReason.UNSUPPORTED_LANGUAGE)

    if size is not None:
        if size == 0:
            return PathDecision(skip_reason=SkipReason.EMPTY)
        if size > settings.MAX_FILE_SIZE_BYTES:
            return PathDecision(skip_reason=SkipReason.TOO_LARGE)
    return PathDecision(language=language)


def _looks_generated(text: str) -> bool:
    head = "\n".join(text[:2000].splitlines()[:10]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def _looks_minified(text: str) -> bool:
    if len(text) < 2000:
        return False
    lines = text.splitlines() or [text]
    longest = max(len(line) for line in lines)
    average = len(text) / len(lines)
    return longest > 3000 or average > 300


def classify_content(data: bytes) -> Union[str, SkipReason]:
    """Return the decoded text if the content should be indexed, else a SkipReason."""
    if not data:
        return SkipReason.EMPTY
    if len(data) > settings.MAX_FILE_SIZE_BYTES:
        return SkipReason.TOO_LARGE
    if b"\x00" in data[:BINARY_SNIFF_BYTES]:
        return SkipReason.BINARY
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return SkipReason.NON_UTF8
    if text.startswith("﻿"):
        text = text[1:]
    if _looks_generated(text):
        return SkipReason.GENERATED
    if _looks_minified(text):
        return SkipReason.MINIFIED
    return text
